/**
 * Единая размерная шкала дизайн-системы.
 *
 * В DS нет «размера компонента» как токена — есть шкалы отступов, радиусов и
 * типографики. `TDsSize` — соглашение ui-kit: каждый размер маппится в пресет
 * этих токенов внутри компонента.
 *
 * Размер наследуется через класс: компонент ставит класс `S|M|L|XL` на хост,
 * а стили резолвят его через `:host-context(.S)` — поэтому карточка может не
 * задавать свой размер и подхватить класс с любого предка. Если ни на хосте,
 * ни на предках размера нет — действует дефолт `M` (базовые стили компонента).
 */
export type TDsSize = 'S' | 'M' | 'L' | 'XL';
